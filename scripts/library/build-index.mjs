import { createHash } from "node:crypto";
import { admittedItems } from "./admission.mjs";
import { Buffer } from "node:buffer";
import { readFileSync, writeFileSync, statSync, existsSync, mkdirSync } from "node:fs";
import { canonicalLibraryId } from "../../src/library/ids.ts";
import { buildIndex } from "../../src/library/search.ts";
import { TOPICS } from "../../src/explore/content.ts";
const output = process.argv.includes("--output-dir") ? process.argv[process.argv.indexOf("--output-dir") + 1] : "src/library";
mkdirSync(output, { recursive: true });
const authored = JSON.parse(readFileSync("content/library/items.json", "utf8"));
const aliases = JSON.parse(readFileSync("content/library/search-aliases.json", "utf8"));
const fixtures = process.env.EXPO_PUBLIC_LIBRARY_FIXTURES === "1";
const preview = process.env.EXPO_PUBLIC_LIBRARY_PREVIEW === "1";
const items = admittedItems(authored, { preview, fixtures });
const categories = { oceans: "ocean", world: "guam", animals: "animals", space: "space", weather: "weather" };
const ids = new Set(items.map((item) => item.id));
const entries = [
  ...items
    .filter((item) => item.type !== "collection")
    .map((item) => ({
      id: item.id,
      title: item.title,
      category: item.category,
      aliases: item.aliases,
      tags: [
        ...item.tags,
        ...(item.type === "topic"
          ? Object.values(item.layers)
              .flat()
              .map((s) => s.text)
          : item.type === "book"
            ? item.pages.flatMap((p) => p.sentences.map((s) => s.text))
            : []),
      ],
    })),
  ...TOPICS.filter((topic) => !ids.has(canonicalLibraryId(topic.id))).map((topic) => ({
    id: topic.id,
    title: topic.title,
    category: categories[topic.world],
    aliases: aliases[topic.id] ?? [],
    tags: [topic.world, topic.short, topic.deeper, topic.question],
  })),
];
const index = buildIndex(entries);
const files = new Set();
const images = new Set();
const sentences = items.flatMap((item) => [
  item.label,
  ...(item.type === "topic"
    ? Object.values(item.layers).flat()
    : item.type === "book"
      ? item.pages.flatMap((page) => page.sentences)
      : []),
]);
for (const item of items) {
  images.add(item.image.path);
  if (item.type === "book") for (const page of item.pages) images.add(page.image.path);
}
// Preserve the reviewed SVG bytes as inline local vectors on native and web.
const rasters = [...images].filter((path) => /\.(png|jpe?g|webp)$/i.test(path));
rasters.forEach((path) => files.add(path));
const vectors = Object.fromEntries([...images].filter((path) => /\.svg$/i.test(path)).map((path) => [path, readFileSync(path, "utf8")]));
const speech = JSON.parse(readFileSync("scripts/learn/library.json", "utf8"));
const clipReceipt = existsSync("scripts/library/audio-receipt.json") ? JSON.parse(readFileSync("scripts/library/audio-receipt.json", "utf8")) : undefined;
const speechPaths = {};
if (items.length && !fixtures) {
  if (!clipReceipt || clipReceipt.voice !== "af_heart" || clipReceipt.networkPlayback !== false) throw new Error("Generate the local warm Library bank before admission");
  for (const [key, text] of Object.entries(speech)) {
    const clip = clipReceipt.clips[key];
    const hash = (bytes) => createHash("sha256").update(bytes).digest("hex");
    if (!clip || clip.path !== `assets/audio/${key}.m4a` || clip.transcriptSha256 !== hash(text) || !existsSync(clip.path) || hash(readFileSync(clip.path)) !== clip.sha256) throw new Error(`Missing/stale local Library audio: ${key}`);
    files.add(clip.path);
    speechPaths[key] = clip.path;
  }
}
for (const sentence of sentences) if (sentence.audio.status === "ready") files.add(sentence.audio.path);
const bytes =
  [...files].reduce((sum, path) => sum + statSync(path).size, 0) + Buffer.byteLength(JSON.stringify({ items, index, vectors, speechPaths }));
if (bytes > 300_000_000) throw new Error(`Library exceeds 300 MB incremental budget: ${bytes} bytes`);
if (Buffer.byteLength(JSON.stringify(index)) > 1_000_000) throw new Error("Library index exceeds 1 MB");
writeFileSync(`${output}/catalog.generated.json`, JSON.stringify({ items, index, bytes, fixtures, preview }, null, 2) + "\n");
const imports = [...files]
  .map((path) => `  ${JSON.stringify(path)}: require(${JSON.stringify("../../" + path)}),`)
  .join("\n");
writeFileSync(
  `${output}/assets.generated.ts`,
  `// Generated by library:index. Local, admitted Library assets only.\nexport const libraryAssets: Record<string, number> = {\n${imports}\n};\n`
);
console.log(
  `Built offline Library index: ${index.length} entries; ${items.length} authored items; ${bytes} bytes${preview ? "; family preview enabled (not approved for shipping)" : fixtures ? "; QA fixtures enabled (not a release)" : ""}.`
);

writeFileSync(`${output}/vectors.generated.ts`, `// Generated from unchanged reviewed Library art.\nexport const libraryVectors: Record<string, string> = ${JSON.stringify(vectors, null, 2)};\n`);
const speechImport = Object.keys(speechPaths).length ? 'import { libraryAssets } from "./assets.generated";\n' : '';
writeFileSync(`${output}/speech.generated.ts`, `// Generated local warm recordings; generation is not audible approval.\n${speechImport}export const librarySpeech: Record<string, number> = {\n${Object.entries(speechPaths).map(([key, path]) => `  ${JSON.stringify(key)}: libraryAssets[${JSON.stringify(path)}],`).join("\n")}\n};\n`);

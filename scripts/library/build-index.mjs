import { Buffer } from "node:buffer";
import { readFileSync, writeFileSync, statSync } from "node:fs";
import { buildIndex } from "../../src/library/search.ts";
import { TOPICS } from "../../src/explore/content.ts";
const authored = JSON.parse(readFileSync("content/library/items.json", "utf8"));
const aliases = JSON.parse(readFileSync("content/library/search-aliases.json", "utf8"));
const fixtures = process.env.EXPO_PUBLIC_LIBRARY_FIXTURES === "1";
const items = authored.filter((item) => fixtures || item.review.status === "approved");
const categories = { oceans: "ocean", world: "guam", animals: "animals", space: "space", weather: "weather" };
const ids = new Set(items.map((item) => item.id));
const entries = [
  ...items
    .filter((item) => item.type !== "collection")
    .map((item) => ({
      id: item.id,
      title: item.title,
      category: item.category,
      aliases: item.aliases,
      tags: [
        ...item.tags,
        ...(item.type === "topic"
          ? Object.values(item.layers)
              .flat()
              .map((s) => s.text)
          : item.type === "book"
            ? item.pages.flatMap((p) => p.sentences.map((s) => s.text))
            : []),
      ],
    })),
  ...TOPICS.filter((topic) => !ids.has(topic.id)).map((topic) => ({
    id: topic.id,
    title: topic.title,
    category: categories[topic.world],
    aliases: aliases[topic.id] ?? [],
    tags: [topic.world, topic.short, topic.deeper, topic.question],
  })),
];
const index = buildIndex(entries);
const files = new Set();
const images = new Set();
const sentences = items.flatMap((item) => [
  item.label,
  ...(item.type === "topic"
    ? Object.values(item.layers).flat()
    : item.type === "book"
      ? item.pages.flatMap((page) => page.sentences)
      : []),
]);
for (const item of items) {
  images.add(item.image.path);
  if (item.type === "book") for (const page of item.pages) images.add(page.image.path);
}
// Vector motifs are rendered by LibraryArt; only raster files need Metro asset imports.
const rasters = [...images].filter((path) => /\.(png|jpe?g|webp)$/i.test(path));
rasters.forEach((path) => files.add(path));
for (const sentence of sentences) if (sentence.audio.status === "ready") files.add(sentence.audio.path);
const bytes =
  [...files].reduce((sum, path) => sum + statSync(path).size, 0) + Buffer.byteLength(JSON.stringify({ items, index }));
if (bytes > 300_000_000) throw new Error(`Library exceeds 300 MB incremental budget: ${bytes} bytes`);
if (Buffer.byteLength(JSON.stringify(index)) > 1_000_000) throw new Error("Library index exceeds 1 MB");
writeFileSync("src/library/catalog.generated.json", JSON.stringify({ items, index, bytes, fixtures }, null, 2) + "\n");
const imports = [...files]
  .map((path) => `  ${JSON.stringify(path)}: require(${JSON.stringify("../../" + path)}),`)
  .join("\n");
writeFileSync(
  "src/library/assets.generated.ts",
  `// Generated by library:index. Local, admitted Library assets only.\nexport const libraryAssets: Record<string, number> = {\n${imports}\n};\n`
);
console.log(
  `Built offline Library index: ${index.length} entries; ${items.length} authored items; ${bytes} bytes${fixtures ? "; QA fixtures enabled (not a release)" : ""}.`
);

/**
 * A3a certification (AR-03, AR-04, AR-05). Writes the certified seed pools and pars that the engines
 * read, from legal 60 Hz witness replays with Helper off and on:
 * - Rail Parade: eight seeds per level whose route witness clears with no bump; par is the longest
 *   witnessed route with an 8% margin, rounded up to 5 steps.
 * - Crab Crossing: eight traffic phases per level whose crossing witness clears with no bump; par is
 *   the most hops any witness used (waiting is not a hop) with a 10% margin.
 * - Palm Patrol: aim and time pars from the steady replay pace over eight seeds (see palm-replay.ts).
 * Run with `npm run arcade:certify`. tests/arcade-curves-a3a.test.ts replays every pooled seed again.
 */
import { writeFileSync } from "node:fs";
import { railLevels } from "../../src/arcade/games/rail-parade/engine";
import { crabLevels } from "../../src/arcade/games/crab-crossing/engine";
import { crabWitness, railWitness } from "../../tests/helpers/arcade-pilots";

const POOL = 8;
const only = process.argv.slice(2);
const want = (game: string) => !only.length || only.includes(game);
/** A level-specific, reproducible candidate order (the engines' own LCG). */
function* candidates(start: number, modulo = 0x100000000): Generator<number> {
  const seen = new Set<number>();
  let x = start >>> 0;
  for (let i = 0; i < 4 * modulo && seen.size < modulo; i++) {
    x = (Math.imul(x, 1664525) + 1013904223) >>> 0;
    const seed = modulo === 0x100000000 ? x : x % modulo;
    if (!seen.has(seed)) { seen.add(seed); yield seed; }
  }
}
/** Writes a generated TypeScript module, so worklet-compiled engines can import it like any other source. */
const write = (file: string, type: string, levels: Record<string, unknown>) => writeFileSync(file, `/** Generated by \`npm run arcade:certify\` (scripts/arcade/certify-curves.ts). Do not edit by hand. */\nexport const certified: { version: 1; levels: Record<string, ${type}> } = ${JSON.stringify({ version: 1, levels }, null, 1)};\n`);

if (want("rail-parade")) {
  const levels: Record<string, { seeds: number[]; par: number }> = {};
  railLevels.forEach((level, n) => {
    const seeds: number[] = [];
    let longest = 0, tried = 0;
    for (const seed of candidates(0xa3a0 + n)) {
      if (seeds.length === POOL || tried++ > 400) break;
      const runs = [false, true].map(helper => railWitness(level, seed, helper));
      if (runs.every(r => r.result?.cleared && r.bumps === 0)) { seeds.push(seed); longest = Math.max(longest, ...runs.map(r => r.moves)); }
    }
    if (seeds.length < POOL) throw new Error(`Rail ${level.id}: only ${seeds.length} certified seeds in ${tried} tries`);
    levels[level.id] = { seeds, par: Math.ceil(longest * 1.08 / 5) * 5 };
    console.log(`rail ${level.id} tried ${tried} longest ${longest} par ${levels[level.id].par}`);
  });
  write("src/arcade/games/rail-parade/certified.ts", "{ seeds: number[]; par: number }", levels);
}

if (want("crab-crossing")) {
  const levels: Record<string, { seeds: number[]; par: number }> = {};
  crabLevels.forEach((level, n) => {
    const seeds: number[] = [];
    let most = 0, tried = 0;
    // Lanes use seed % 100 as their phase, so candidates are the 100 distinct phases.
    for (const seed of candidates(0xc4a0 + n, 100)) {
      if (seeds.length === POOL) break;
      tried++;
      const runs = [false, true].map(helper => { try { return crabWitness(level, seed, helper); } catch { return null; } });
      if (runs.every(r => r?.result?.cleared && r.bumps === 0)) { seeds.push(seed); most = Math.max(most, ...runs.map(r => r!.hops)); }
    }
    if (seeds.length < POOL) throw new Error(`Crab ${level.id}: only ${seeds.length} certified phases in ${tried} tries`);
    levels[level.id] = { seeds, par: Math.ceil(most * 1.1) };
    console.log(`crab ${level.id} tried ${tried} most hops ${most} par ${levels[level.id].par}`);
  });
  write("src/arcade/games/crab-crossing/certified.ts", "{ seeds: number[]; par: number }", levels);
}

if (want("palm-patrol")) {
  // Palm pars read the engine, so they are imported only when Palm is being certified.
  const { palmLevels } = await import("../../src/arcade/games/palm-patrol/engine");
  const { palmParsFromReplays } = await import("../../tests/helpers/palm-replay");
  const levels = palmParsFromReplays(palmLevels);
  for (const [id, p] of Object.entries(levels)) console.log(`palm ${id} par ${p.par}s aim ${p.accuracy}`);
  write("src/arcade/games/palm-patrol/certified.ts", "{ par: number; accuracy: number }", levels);
}

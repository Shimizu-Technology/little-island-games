// Builds the island picture dictionary from the drawing definitions:
//   content/pictures/svg/<id>.svg      one vector file per picture
//   content/pictures/manifest.json     id, word, category, alt text, bytes, sha256 (what the app reads)
//   content/pictures/sources.json      word id, allowlist queue, chosen meaning (what reviewers read)
//   content/pictures/approvals.json    empty person-review fields, bound to each file's hash
//   src/content/pictures/assets.generated.ts   lazy require table
// `node scripts/art/pictures/build.mjs` writes; `--check` only compares.
import { admitGenerated } from '../../words/generated-admission.mjs';
import { Buffer } from 'node:buffer';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { svg, VIEWBOX } from './style.mjs';
import { definitions, CATEGORIES } from './defs/index.mjs';

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
export const OUT = join(ROOT, 'content/pictures');
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
const json = value => `${JSON.stringify(value, null, 2)}\n`;

/** Every output file, keyed by repository path. Pure: the check compares this with the tree. */
export function buildOutputs(defs = definitions()) {
  admitGenerated(ROOT,'pictures',defs.map(d=>d.word));
  const files = new Map();
  const pictures = [], sources = [], approvals = [];
  const previous = existsSync(join(OUT, 'approvals.json')) ? JSON.parse(readFileSync(join(OUT, 'approvals.json'), 'utf8')) : { pictures: [] };
  const kept = new Map(previous.pictures.map(a => [a.id, a]));
  const allow = existsSync(join(OUT, 'allowlist.json')) ? JSON.parse(readFileSync(join(OUT, 'allowlist.json'), 'utf8')).words : {};
  for (const d of defs) {
    const text = svg(d.draw());
    const bytes = Buffer.byteLength(text);
    const hash = sha256(text);
    files.set(`content/pictures/svg/${d.id}.svg`, text);
    pictures.push({ id: d.id, word: d.word, category: d.category, alt: d.alt, bytes, sha256: hash });
    sources.push({ id: d.id, wordId: `en-${d.word.toLowerCase()}`, queue: allow[d.word]?.queue ?? null, meaning: d.meaning, ...(d.otherMeaning ? { otherMeaning: d.otherMeaning } : {}), ...(d.basedOn ? { basedOn: d.basedOn } : {}) });
    // A decision only stands for the exact bytes it was made on; a redraw clears it.
    const old = kept.get(d.id);
    approvals.push(old && old.sha256 === hash ? old : { id: d.id, sha256: hash, leon: { decision: null, date: null, note: null } });
  }
  const totalBytes = pictures.reduce((s, p) => s + p.bytes, 0);
  files.set('content/pictures/manifest.json', json({ schemaVersion: 1, viewBox: VIEWBOX, count: pictures.length, totalBytes, categories: CATEGORIES, pictures }));
  files.set('content/pictures/sources.json', json({ schemaVersion: 1, allowlist: 'W1 word pipeline queues (tiers.queue.json, local.queue.json); see content/pictures/README.md', pictures: sources }));
  files.set('content/pictures/approvals.json', json({ schemaVersion: 1, note: 'Leon fills these in. A redraw changes the hash and clears the decision.', pictures: approvals }));
  const table = pictures.map(p => `  ${JSON.stringify(p.id)}: () => require(${JSON.stringify(`../../../content/pictures/svg/${p.id}.svg`)}),`).join('\n');
  files.set('src/content/pictures/assets.generated.ts', `// Generated by scripts/art/pictures/build.mjs. Do not edit.\nexport const pictureAssets: Record<string, () => number> = {\n${table}\n};\n`);
  return files;
}

/** Paths that differ from what the definitions produce, including stray SVGs. */
export function staleOutputs(files = buildOutputs()) {
  const stale = [];
  for (const [path, text] of files) if (!existsSync(join(ROOT, path)) || readFileSync(join(ROOT, path), 'utf8') !== text) stale.push(path);
  const dir = join(OUT, 'svg');
  if (existsSync(dir)) for (const name of readdirSync(dir)) if (!files.has(`content/pictures/svg/${name}`)) stale.push(`content/pictures/svg/${name}`);
  return stale;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const files = buildOutputs();
  if (process.argv.includes('--check')) {
    const stale = staleOutputs(files);
    if (stale.length) { console.error(`Out of date:\n${stale.join('\n')}`); process.exit(1); }
    console.log(`Pictures up to date: ${files.size} files.`);
  } else {
    rmSync(join(OUT, 'svg'), { recursive: true, force: true });
    for (const [path, text] of files) { mkdirSync(dirname(join(ROOT, path)), { recursive: true }); writeFileSync(join(ROOT, path), text); }
    const m = JSON.parse(files.get('content/pictures/manifest.json'));
    console.log(`Wrote ${m.count} pictures, ${m.totalBytes} bytes of SVG.`);
  }
}

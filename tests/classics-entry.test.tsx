(globalThis as typeof globalThis & { IS_REACT_ACT_ENVIRONMENT: boolean }).IS_REACT_ACT_ENVIRONMENT = true;
const words = (n: ReactTestRenderer["root"] | string): string => typeof n === "string" ? n : n.children.map(words).join("");
const button = (r: ReactTestRenderer, text: string) => r.root.find(n => n.type === "button" && words(n) === text);
afterEach(() => { fixture.focused = true; fixture.sessions = {}; fixture.push.mockReset(); fixture.update.mockReset(); });
it("fresh Classics setup opens Challenge without a blocking modal or creating a round", async () => {
  let r!: ReactTestRenderer;
  await act(() => { r = create(<Play/>); });
  expect(words(r.root)).toContain("Try to draw");
  await act(() => button(r, "Fork puzzles · spot two winning threats").props.onPress());
  expect(fixture.push).toHaveBeenCalledWith({ pathname: "/challenge", params: { game: "tic-tac-toe" } });
  fixture.focused = false; await act(() => r.update(<Play/>));
  expect(r.root.findAllByType("aside")).toHaveLength(0);
  expect(fixture.update).not.toHaveBeenCalled();
  fixture.focused = true; await act(() => r.update(<Play/>));
  expect(words(r.root)).toContain("Start playing");
  await act(() => r.unmount());
});
it("a saved Classic round survives entry from its options sheet", async () => {
  const saved = createTic(defaultOptions); fixture.sessions = { "tic-tac-toe": saved }; let r!: ReactTestRenderer;
  await act(() => { r = create(<Play/>); });
  await act(() => button(r, "New round & options").props.onPress());
  const choices = r.root.findAll(n => n.type === "button" && words(n) === "Fork puzzles · spot two winning threats");
  await act(() => choices.at(-1)!.props.onPress());
  fixture.focused = false; await act(() => r.update(<Play/>));
  expect(r.root.findAllByType("aside")).toHaveLength(0);
  expect(fixture.sessions["tic-tac-toe"]).toBe(saved);
  expect(fixture.update).not.toHaveBeenCalled();
  fixture.focused = true; await act(() => r.update(<Play/>));
  expect(r.root.findAllByType("aside")).toHaveLength(0);
  await act(() => r.unmount());
});

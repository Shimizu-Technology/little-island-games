it('F4 hides the reader title and actions, retaining saved data until Books is re-enabled', async () => {
  const child = { ...newLibraryChild(), saved: ['busy-day'], bookPages: { 'busy-day': 4 } };
  child.policy.collections = child.policy.collections.filter(c => c !== 'books');
  fixture.store = { ready: true, epoch: 1, save: { ...emptySave(), library: { version: 2, profiles: { family: child } } }, libraryPatch: vi.fn(() => true) };
  let root!: ReturnType<typeof create>;
  await act(async () => { root = create(<LibraryScreen />); });
  expect(JSON.stringify(root.toJSON())).not.toContain('A very busy day!');
  expect(root.root.findAllByProps({ label: 'Book information' })).toHaveLength(0);
  expect(root.root.findAllByProps({ label: 'Saved book. Remove from My Shelf' })).toHaveLength(0);
  expect(JSON.stringify(root.toJSON())).toContain('Island Library');
  const saved = structuredClone({ saved: child.saved, bookPages: child.bookPages });
  child.policy.collections = [...child.policy.collections, 'books'];
  await act(async () => { root.update(<LibraryScreen />); });
  expect(JSON.stringify(root.toJSON())).toContain('A very busy day!');
  expect(root.root.findAllByProps({ label: 'Book information' })).toHaveLength(1);
  expect(root.root.findAllByProps({ label: 'Saved book. Remove from My Shelf' })).toHaveLength(1);
  expect(root.root.findByType('Reader' as any).props.page).toBe(4);
  expect({ saved: child.saved, bookPages: child.bookPages }).toEqual(saved);
  await act(async () => root.unmount());
});
